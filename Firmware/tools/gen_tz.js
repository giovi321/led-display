// Generates Firmware/main/tzdata.c: IANA zone name -> POSIX TZ rule.
// Run with a Node build that has full ICU (node --version >= 14 bundles it).
//
//   node gen_tz.js > tzdata.c
//
// The rules are derived by probing Intl for the reference year below and
// finding the daylight-saving transitions, so the output is only as current
// as the running Node's tzdata.

const YEAR = 2027;

function offsetMinutes(tz, date) {
  const dtf = new Intl.DateTimeFormat('en-US', {
    timeZone: tz, hour12: false,
    year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit',
  });
  const m = {};
  for (const p of dtf.formatToParts(date)) m[p.type] = p.value;
  const asUTC = Date.UTC(+m.year, +m.month - 1, +m.day,
                         (+m.hour) % 24, +m.minute, +m.second);
  return Math.round((asUTC - date.getTime()) / 60000);
}

// All instants in YEAR where the offset changes, to the minute.
function transitions(tz) {
  const out = [];
  const start = Date.UTC(YEAR, 0, 1);
  const end = Date.UTC(YEAR + 1, 0, 1);
  const DAY = 86400000;
  let prev = offsetMinutes(tz, new Date(start));
  for (let t = start + DAY; t <= end; t += DAY) {
    const cur = offsetMinutes(tz, new Date(t));
    if (cur !== prev) {
      // Narrow to the minute inside this day.
      let lo = t - DAY, hi = t;
      while (hi - lo > 60000) {
        const mid = lo + Math.floor((hi - lo) / 2 / 60000) * 60000;
        if (mid === lo) break;
        if (offsetMinutes(tz, new Date(mid)) === prev) lo = mid; else hi = mid;
      }
      out.push({ at: hi, from: prev, to: cur });
      prev = cur;
    }
  }
  return out;
}

// POSIX writes offsets with the opposite sign of UTC offsets: UTC+1 is "-1".
function posixOffset(mins) {
  const inv = -mins;
  const sign = inv < 0 ? '-' : '';
  const a = Math.abs(inv);
  const h = Math.floor(a / 60), m = a % 60;
  return sign + h + (m ? ':' + String(m).padStart(2, '0') : '');
}

// An abbreviation POSIX will accept: letters if the zone has a real one,
// otherwise the bracketed numeric form (<+0530>), which newlib parses too.
function abbrev(tz, date, mins) {
  const dtf = new Intl.DateTimeFormat('en-US', { timeZone: tz, timeZoneName: 'short' });
  let name = '';
  for (const p of dtf.formatToParts(date)) if (p.type === 'timeZoneName') name = p.value;
  if (/^[A-Za-z]{3,5}$/.test(name)) return name;
  const sign = mins < 0 ? '-' : '+';
  const a = Math.abs(mins);
  const h = String(Math.floor(a / 60)).padStart(2, '0'), m = a % 60;
  return '<' + sign + h + (m ? String(m).padStart(2, '0') : '') + '>';
}

// POSIX Mm.w.d/h for a transition instant, expressed in the local time in
// force just before it (standard time for the DST start, daylight time for
// the end - which is what POSIX asks for in each position).
function rule(at, fromMins) {
  const local = new Date(at + fromMins * 60000);
  const month = local.getUTCMonth() + 1;
  const dow = local.getUTCDay();
  const dom = local.getUTCDate();
  let week = Math.floor((dom - 1) / 7) + 1;
  // "5" means the last such weekday of the month, not literally the fifth.
  const daysInMonth = new Date(Date.UTC(local.getUTCFullYear(), month, 0)).getUTCDate();
  if (dom + 7 > daysInMonth) week = 5;
  const h = local.getUTCHours(), mi = local.getUTCMinutes();
  let time = '';
  if (h !== 2 || mi !== 0) time = '/' + h + (mi ? ':' + String(mi).padStart(2, '0') : '');
  return `M${month}.${week}.${dow}${time}`;
}

function posixFor(tz) {
  const jan = new Date(Date.UTC(YEAR, 0, 15));
  const tr = transitions(tz);
  if (tr.length === 0) {
    const off = offsetMinutes(tz, jan);
    return abbrev(tz, jan, off) + posixOffset(off);
  }
  if (tr.length !== 2) return null;   // not expressible as a POSIX rule pair
  // The transition that moves the clock forward starts DST.
  const fwd = tr.find(t => t.to > t.from);
  const back = tr.find(t => t.to < t.from);
  if (!fwd || !back) return null;
  const stdMins = fwd.from, dstMins = fwd.to;
  const stdAb = abbrev(tz, new Date(back.at + 86400000 * 30), stdMins);
  const dstAb = abbrev(tz, new Date(fwd.at + 86400000 * 30), dstMins);
  return stdAb + posixOffset(stdMins) + dstAb + posixOffset(dstMins) +
         ',' + rule(fwd.at, fwd.from) + ',' + rule(back.at, back.from);
}

const zones = Intl.supportedValuesOf('timeZone').slice().sort();
const entries = [];
const skipped = [];
for (const tz of zones) {
  const p = posixFor(tz);
  if (p) entries.push([tz, p]); else skipped.push(tz);
}

// Dedupe the rule strings: most zones share a handful of them.
const rules = [];
const ruleIndex = new Map();
for (const [, p] of entries) {
  if (!ruleIndex.has(p)) { ruleIndex.set(p, rules.length); rules.push(p); }
}

const esc = s => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
let out = '';
out += '// Generated by tools/gen_tz.js - do not edit by hand.\n';
out += `// Source: Node ICU tzdata, rules sampled for ${YEAR}.\n`;
out += '//\n';
out += '// Regenerate when the IANA database changes a rule that matters to you:\n';
out += '//   node Firmware/tools/gen_tz.js > Firmware/main/tzdata.c\n';
out += '//\n';
out += `// ${entries.length} zones, ${rules.length} distinct POSIX rules.\n`;
if (skipped.length) {
  out += `// Not expressible as a single POSIX rule pair, omitted: ${skipped.join(', ')}\n`;
}
out += '\n#include "tz.h"\n\n';
out += 'const char *const tz_rules[] = {\n';
for (const r of rules) out += `    "${esc(r)}",\n`;
out += '};\n\n';
out += 'const tz_entry_t tz_zones[] = {\n';
for (const [name, p] of entries) {
  out += `    {"${esc(name)}", ${ruleIndex.get(p)}},\n`;
}
out += '};\n\n';
out += 'const size_t tz_zone_count = sizeof(tz_zones) / sizeof(tz_zones[0]);\n';
out += 'const size_t tz_rule_count = sizeof(tz_rules) / sizeof(tz_rules[0]);\n';

process.stdout.write(out);
process.stderr.write(`zones=${entries.length} rules=${rules.length} skipped=${skipped.length}\n`);
if (skipped.length) process.stderr.write('skipped: ' + skipped.join(', ') + '\n');
